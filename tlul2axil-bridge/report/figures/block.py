import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
fig,ax=plt.subplots(figsize=(10,3.9)); ax.axis("off"); ax.set_xlim(0,100); ax.set_ylim(-1,36)
def box(x,y,w,h,t,fc="#eef3f8",ls="-",fs=8.5):
    ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle="round,pad=0.3,rounding_size=1.0",fc=fc,ec="#1f4e79",lw=1.2,ls=ls))
    if t: ax.text(x+w/2,y+h/2,t,ha="center",va="center",fontsize=fs)
def arr(x1,y1,x2,y2):
    ax.annotate("",xy=(x2,y2),xytext=(x1,y1),arrowprops=dict(arrowstyle="->",color="#333",lw=1.1))
